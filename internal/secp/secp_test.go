func unhex(t *testing.T, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func TestBIP340Vectors(t *testing.T) {
	for i, v := range bip340 {
		pub, msg, sig := unhex(t, v.pub), unhex(t, v.msg), unhex(t, v.sig)
		if v.secret != "" {
			secret := unhex(t, v.secret)
			got, err := PublicKey(secret)
			if err != nil || got != strings.ToLower(v.pub) {
				t.Errorf("#%d: public key %s, %v", i, got, err)
			}
			var aux [32]byte
			copy(aux[:], unhex(t, v.aux))
			signed, err := Sign(secret, msg, aux)
			if err != nil || !strings.EqualFold(hex.EncodeToString(signed[:]), v.sig) {
				t.Errorf("#%d: signature %x, %v", i, signed, err)
			}
		}
		if got := Verify(pub, msg, sig); got != v.valid {
			t.Errorf("#%d: Verify = %v, want %v", i, got, v.valid)
		}
	}
}

// BIP-340 fails a signature whose r is the field size or above, or whose s is the curve's
// order or above: btcec reduces s silently, so Verify checks it first.
func TestVerifyRefusesOutOfRangeScalars(t *testing.T) {
	pub := unhex(t, "DFF1D77F2A671C5F36183726DB2341BE58FEAE1DA2DECED843240F7B502BA659")
	msg := unhex(t, "243F6A8885A308D313198A2E03707344A4093822299F31D0082EFA98EC4E6C89")
	n := btcec.S256().N.Bytes()
	p := btcec.S256().P.Bytes()
	for name, sig := range map[string][]byte{
		"r = p": append(p, unhex(t, "69E89B4C5564D00349106B8497785DD7D1D713A8AE82B32FA79D5F7FC407D39B")...),
		"s = n": append(unhex(t, "6CFF5C3BA86C69EA4B7376F31A9BCB4F74C1976089B2D9963DA2E5543E177769"), n...),
	} {
		if Verify(pub, msg, sig) {
			t.Errorf("%s verified", name)
		}
	}
	// The check itself: a valid signature whose s is read modulo n would be another encoding.
	var s btcec.ModNScalar
	if !s.SetByteSlice(n) {
		t.Error("n does not overflow")
	}
}

func TestSecretKeysAreNeverReduced(t *testing.T) {
	n := btcec.S256().N.Bytes()
	zero := make([]byte, 32)
	one := make([]byte, 32)
	one[31] = 1
	for name, secret := range map[string][]byte{"zero": zero, "n": n, "ff": unhex(t, strings.Repeat("ff", 32)), "short": one[1:]} {
		if IsSecretKey(secret) {
			t.Errorf("%s is a secret key", name)
		}
		if _, err := PublicKey(secret); err == nil {
			t.Errorf("%s has a public key", name)
		}
		if _, err := Sign(secret, make([]byte, 32), [32]byte{}); err == nil {
			t.Errorf("%s signs", name)
		}
	}
	if !IsSecretKey(one) {
		t.Error("1 is a secret key")
	}
}

func TestPublicKeys(t *testing.T) {
	if !IsPublicKey("dff1d77f2a671c5f36183726db2341be58feae1da2deced843240f7b502ba659") {
		t.Error("a point refused")
	}
	for _, v := range []any{
		"DFF1D77F2A671C5F36183726DB2341BE58FEAE1DA2DECED843240F7B502BA659", // upper case
		"eefdea4cdb677750a420fee807eacf21eb9898ae79b9768766e4faa04a2d4a34", // not on the curve
		"fffffffffffffffffffffffffffffffffffffffffffffffffffffffefffffc30", // above the field size
		"dff1d77f2a671c5f36183726db2341be58feae1da2deced843240f7b502ba6",   // short
		nil, 1.0,
	} {
		if IsPublicKey(v) {
			t.Errorf("%v is a public key", v)
		}
	}
}

func TestSharedX(t *testing.T) {
	a, b := make([]byte, 32), make([]byte, 32)
	a[31], b[31] = 3, 7
	pubA, _ := PublicKey(a)
	pubB, _ := PublicKey(b)
	ab, err1 := SharedX(a, unhex(t, pubB))
	ba, err2 := SharedX(b, unhex(t, pubA))
	if err1 != nil || err2 != nil || hex.EncodeToString(ab) != hex.EncodeToString(ba) || len(ab) != 32 {
		t.Error("ECDH")
	}
	if _, err := SharedX(a, unhex(t, "eefdea4cdb677750a420fee807eacf21eb9898ae79b9768766e4faa04a2d4a34")); err == nil {
		t.Error("ECDH with a point off the curve")
	}
}
